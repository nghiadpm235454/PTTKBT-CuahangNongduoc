USE CuahangNongduoc;
GO

IF COL_LENGTH('dbo.THAM_SO', 'PP_XUAT_KHO') IS NULL
    ALTER TABLE dbo.THAM_SO ADD PP_XUAT_KHO NVARCHAR(20) NOT NULL
        CONSTRAINT DF_THAM_SO_PP_XUAT_KHO DEFAULT N'FIFO';      -- FIFO | CHI_DINH
GO

IF COL_LENGTH('dbo.THAM_SO', 'PP_GIA_XUAT') IS NULL
    ALTER TABLE dbo.THAM_SO ADD PP_GIA_XUAT NVARCHAR(20) NOT NULL
        CONSTRAINT DF_THAM_SO_PP_GIA_XUAT DEFAULT N'BQGQ';      -- BQGQ | FIFO
GO

IF COL_LENGTH('dbo.CHI_TIET_PHIEU_BAN', 'GIA_XUAT') IS NULL
    ALTER TABLE dbo.CHI_TIET_PHIEU_BAN ADD GIA_XUAT INT NULL;   -- gia xuat da tinh (theo PP_GIA_XUAT)
GO
