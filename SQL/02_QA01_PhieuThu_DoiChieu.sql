-- Kết quả phải có Khop = 1
SELECT PB.ID, PB.TONG_TIEN,
       PB.TIEN_HANG + ISNULL(PB.TONG_DICH_VU,0) + ISNULL(PB.PHI_VAN_CHUYEN,0)
         - ISNULL(PB.CHIET_KHAU,0) - ISNULL(PB.TIEN_KHUYEN_MAI,0) - ISNULL(PB.TIEN_GIAM_GIA,0) AS TongTinhLai,
       CASE WHEN PB.TONG_TIEN = PB.TIEN_HANG + ISNULL(PB.TONG_DICH_VU,0) + ISNULL(PB.PHI_VAN_CHUYEN,0)
              - ISNULL(PB.CHIET_KHAU,0) - ISNULL(PB.TIEN_KHUYEN_MAI,0) - ISNULL(PB.TIEN_GIAM_GIA,0)
            THEN 1 ELSE 0 END AS Khop,
       (SELECT SUM(SO_TIEN) FROM CHI_TIET_DICH_VU_PHIEU_BAN WHERE ID_PHIEU_BAN = PB.ID) AS TongDV_ChiTiet,
       (SELECT SUM(THANH_TIEN) FROM CHI_TIET_PHIEU_BAN WHERE ID_PHIEU_BAN = PB.ID) AS TongHang_ChiTiet
FROM PHIEU_BAN PB
WHERE PB.ID = 'DEMO-PB-HD1';
