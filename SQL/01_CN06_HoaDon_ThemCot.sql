IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='PHIEU_BAN' AND COLUMN_NAME='CHIET_KHAU')
    ALTER TABLE PHIEU_BAN ADD CHIET_KHAU DECIMAL(18,2) NULL;
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='PHIEU_BAN' AND COLUMN_NAME='TIEN_KHUYEN_MAI')
    ALTER TABLE PHIEU_BAN ADD TIEN_KHUYEN_MAI DECIMAL(18,2) NULL;
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='PHIEU_BAN' AND COLUMN_NAME='QUY_TAC_GIAM_GIA')
    ALTER TABLE PHIEU_BAN ADD QUY_TAC_GIAM_GIA NVARCHAR(200) NULL;
GO
