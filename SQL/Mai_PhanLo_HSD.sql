-- 1. Luu so lo + HSD vao chi tiet phieu ban (snapshot luc ban)
IF COL_LENGTH('dbo.CHI_TIET_PHIEU_BAN','SO_LO') IS NULL
    ALTER TABLE dbo.CHI_TIET_PHIEU_BAN ADD SO_LO NVARCHAR(50) NULL;
IF COL_LENGTH('dbo.CHI_TIET_PHIEU_BAN','NGAY_HET_HAN') IS NULL
    ALTER TABLE dbo.CHI_TIET_PHIEU_BAN ADD NGAY_HET_HAN DATETIME NULL;
GO
-- 2. Dien du lieu cu
UPDATE ct SET ct.SO_LO = ct.ID_MA_SAN_PHAM, ct.NGAY_HET_HAN = m.NGAY_HET_HAN
FROM dbo.CHI_TIET_PHIEU_BAN ct JOIN dbo.MA_SAN_PHAM m ON m.ID = ct.ID_MA_SAN_PHAM
WHERE ct.SO_LO IS NULL;
GO
-- 3. Index cho truy van FIFO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_MA_SAN_PHAM_FIFO' AND object_id=OBJECT_ID('dbo.MA_SAN_PHAM'))
    CREATE INDEX IX_MA_SAN_PHAM_FIFO ON dbo.MA_SAN_PHAM (ID_SAN_PHAM, NGAY_HET_HAN, NGAY_NHAP) INCLUDE (SO_LUONG);
GO
